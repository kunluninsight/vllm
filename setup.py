import os
import re
import subprocess

from setuptools import find_packages, setup

ROOT = os.path.dirname(os.path.realpath(__file__))
VERSION_FILE = os.path.join(ROOT, "src", "hisim", "_version.py")
# Base version used until the first release tag exists.
FALLBACK_VERSION = "0.1.0"


def _git(*args):
    return subprocess.check_output(
        ["git", *args], cwd=ROOT, stderr=subprocess.DEVNULL, text=True
    ).strip()


def _version_from_git():
    """PEP 440 version from the nearest `vX.Y.Z` / `X.Y.Z` tag.

    exact clean tag -> X.Y.Z; otherwise X.Y.Z.post<N>+g<sha>[.dirty],
    where N is the commit distance (total commit count when untagged).
    """
    try:
        # Ignore an enclosing repository when the source tree has no .git of its own.
        if os.path.realpath(_git("rev-parse", "--show-toplevel")) != ROOT:
            return None
        sha = _git("rev-parse", "--short", "HEAD")
    except (OSError, subprocess.CalledProcessError):
        return None
    dirty = bool(_git("status", "--porcelain", "--untracked-files=no"))
    try:
        desc = _git(
            "describe", "--tags", "--long", "--match", "v[0-9]*", "--match", "[0-9]*"
        )
        tag, distance, _ = re.fullmatch(r"(.+)-(\d+)-g([0-9a-f]+)", desc).groups()
        base, distance = tag.lstrip("v"), int(distance)
    except (subprocess.CalledProcessError, AttributeError):
        base, distance = FALLBACK_VERSION, int(_git("rev-list", "--count", "HEAD"))

    if distance == 0 and not dirty:
        return base
    version = f"{base}.post{distance}" if distance else base
    return f"{version}+g{sha}" + (".dirty" if dirty else "")


def _version_from_file():
    # Builds without .git (e.g. from an sdist) reuse the previously generated file.
    try:
        with open(VERSION_FILE) as f:
            return re.search(r'__version__ = "(.+)"', f.read()).group(1)
    except (OSError, AttributeError):
        return None


def get_version():
    version = _version_from_git()
    if version is None:
        return _version_from_file() or FALLBACK_VERSION
    with open(VERSION_FILE, "w") as f:
        f.write(
            f'# Generated by setup.py from git; do not edit.\n__version__ = "{version}"\n'
        )
    return version


setup(
    name="hisim",
    version=get_version(),
    description="A high-fidelity LLM inference simulator",
    packages=find_packages(where="src"),
    package_dir={"": "src"},
    data_files=[
        ("/", ["hisim.pth"]),
    ],
)
